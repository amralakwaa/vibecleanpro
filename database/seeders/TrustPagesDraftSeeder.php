    /**
     * @param  list<array{type: string, data: array<string, mixed>, active?: bool}>  $blocks
     * @param  array<string, string>  $seo
     */
    private function fill(string $slug, PageType $type, array $blocks, array $seo): void
    {
        $page = Page::query()->where('slug', $slug)->where('type', $type)->first();

        if (! $page || $page->status !== PageStatus::Draft || $page->contentBlocks()->exists()) {
            return;
        }

        foreach ($blocks as $position => $block) {
            $page->contentBlocks()->create([
                'type' => $block['type'],
                'data' => $block['data'],
                'position' => $position + 1,
                'is_active' => $block['active'] ?? true,
            ]);
        }

        $page->seoMetadata()->updateOrCreate([], [...$seo, 'robots_index' => true, 'robots_follow' => true]);
    }

    /**
     * @return array{type: string, data: array<string, mixed>, active?: bool}
     */
    private static function pending(string $what, bool $active = true): array
    {
        return [
            'type' => 'rich_text',
            'active' => $active,
            'data' => ['content' => '<p><strong>⚠ '.PublishingGate::OWNER_INPUT_MARKER.':</strong> '.$what.'</p>'],
        ];
    }

    /**
     * @param  list<string>  $lines
     * @return array{type: string, data: array<string, mixed>}
     */
    private static function text(array $lines): array
    {
        return ['type' => 'rich_text', 'data' => ['content' => implode("\n", $lines)]];
    }

