/**
 * Content for the three static CMS pages: About, Privacy and Terms.
 *
 * Everything written here is either an operational fact the code can back
 * up (see PRIVACY_DATA_INVENTORY.md) or a stored business-profile value.
 * Every undecided point is a block carrying the "NEEDS OWNER INPUT"
 * marker, which the Publishing Gate refuses to publish - so none of these
 * pages can go live half-decided. Nothing here claims compliance with any
 * regulation.
 *
 * On About the marker blocks are inactive: they are visible to editors in
 * the panel and still block publishing, but a visitor would never see
 * them. On Privacy and Terms the markers sit in the body on purpose -
 * those pages stay drafts until a human replaces each one.
 *
 * Touches a page only while it is a draft with no content blocks, so an
 * edited or published page is never overwritten. It publishes nothing.
 */
